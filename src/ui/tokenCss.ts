/**
 * design/tokens.json → CSS custom properties. Pure, so the generator script and the sync test share it.
 * JSON is canonical (DESIGN §15). Fonts are NOT declared here: the app loads only the weights it uses
 * (src/ui/fonts.css), while design/tokens.css keeps its full @font-face set for design files.
 */
type Json = Record<string, unknown>;
export type Block = Map<string, string>;
export interface TokenBlocks {
  base: Block;
  dark: Block;
  light: Block;
  reduced: Block;
}

const GENERIC = new Set(['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui']);
const num = (n: number, dec: number) => String(parseFloat(n.toFixed(dec)));
const entries = (o: unknown) => Object.entries((o ?? {}) as Json).filter(([k]) => !k.startsWith('_') && !k.startsWith('$'));

export function deriveTokenBlocks(tokens: Json): TokenBlocks {
  const base: Block = new Map();
  const color = tokens.color as Json;
  for (const [k, v] of entries(color)) base.set(`--c-${k}`, String((v as Json).$value));

  const font = tokens.font as Json;
  for (const [k, v] of entries(font.family)) {
    const list = (v as Json).$value as string[];
    base.set(`--f-${k}`, list.map((f) => (GENERIC.has(f) ? f : `"${f}"`)).join(', '));
  }
  // Saildrone fluid scale: clamp between a 20rem and 90rem viewport (DESIGN §3.1, MEASURED).
  for (const [k, v] of entries(font.size_px)) {
    const [min, max] = (v as number[]).map((px) => px / 16) as [number, number];
    if (min === max) base.set(`--fs-${k}`, `${num(min, 4)}rem`);
    else {
      const slope = (max - min) / 70;
      base.set(`--fs-${k}`, `clamp(${num(min, 4)}rem, ${num(min - slope * 20, 3)}rem + ${num(slope * 100, 3)}vw, ${num(max, 4)}rem)`);
    }
  }
  for (const [k, v] of entries(font.weight)) base.set(`--fw-${k}`, String(v));
  for (const [k, v] of entries(font.line_height)) base.set(`--lh-${k}`, String(v));
  for (const [k, v] of entries(font.letter_spacing)) base.set(`--ls-${k}`, String(v));
  // Commissioner flare axis (FLAR 0–100): one dial for "personality by size" (DESIGN §3).
  for (const [k, v] of entries(font.flare)) base.set(`--flare-${k}`, String(v));
  for (const [k, v] of entries(tokens.space)) base.set(k === 'inset-app' ? '--inset-app' : `--s-${k}`, String(v));
  for (const [k, v] of entries(tokens.radius)) base.set(`--r-${k}`, String(v) === '0px' ? '0' : String(v));
  const motion = tokens.motion as Json;
  for (const [k, v] of entries(motion.duration)) base.set(`--t-${k}`, String(v));
  for (const [k, v] of entries(motion.easing)) base.set(`--e-${k}`, `cubic-bezier(${(v as number[]).join(', ')})`);
  for (const [k, v] of entries(tokens.size)) base.set(`--sz-${k}`, String(v));

  const shadow = tokens.shadow as Json;
  const resolve = (v: string): string => {
    const m = /^\{(\w+)\.([\w-]+)\}$/.exec(v);
    if (!m) return v;
    if (m[1] === 'color') return `var(--c-${m[2]})`;
    if (m[1] === 'shadow') return String((shadow[m[2]!] as Json).$value);
    throw new Error(`Unresolvable token reference ${v}`);
  };
  const semantic = tokens.semantic as Json;
  const dark: Block = new Map(entries(semantic.dark).map(([k, v]) => [`--${k}`, resolve(String(v))]));
  const light: Block = new Map(entries(semantic.light).map(([k, v]) => [`--${k}`, resolve(String(v))]));
  const reduced: Block = new Map(entries(motion.reduced).map(([k, v]) => [`--t-${k}`, String(v)]));
  return { base, dark, light, reduced };
}

const render = (selector: string, block: Block, indent = '') =>
  `${indent}${selector} {\n${[...block].map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n')}\n${indent}}\n`;

export function renderTokenCss(b: TokenBlocks): string {
  return [
    '/* GENERATED by scripts/build-tokens.ts from design/tokens.json — do not edit. Run `npm run tokens`. */\n',
    render(':root', b.base),
    render(':root,\n[data-theme="dark"]', b.dark),
    render('[data-theme="light"]', b.light),
    `@media (prefers-reduced-motion: reduce) {\n${render(':root', b.reduced, '  ')}}\n`,
  ].join('\n');
}

/** Parse custom properties from a CSS file into the same four blocks (for the sync test). */
export function parseCssBlocks(css: string): TokenBlocks {
  const noComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const blocks: TokenBlocks = { base: new Map(), dark: new Map(), light: new Map(), reduced: new Map() };
  const media = /@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{([\s\S]*?\})\s*\}/.exec(noComments);
  const rest = media ? noComments.replace(media[0], '') : noComments;
  const fill = (target: Block, body: string) => {
    for (const m of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) target.set(m[1]!, m[2]!.trim());
  };
  if (media) fill(blocks.reduced, media[1]!);
  for (const m of rest.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const sel = m[1]!.replace(/\s+/g, ' ').trim();
    if (sel.startsWith('@font-face')) continue;
    if (sel === ':root') fill(blocks.base, m[2]!);
    else if (sel.includes('[data-theme="dark"]')) fill(blocks.dark, m[2]!);
    else if (sel === '[data-theme="light"]') fill(blocks.light, m[2]!);
  }
  return blocks;
}

/** Canonical comparison form: resolve var(--c-*) to hex, drop quotes and whitespace, lower-case. */
export function normalizeValue(v: string, base: Block): string {
  let out = v;
  for (let i = 0; i < 3; i++) out = out.replace(/var\((--c-[\w-]+)\)/g, (_, name: string) => base.get(name) ?? name);
  return out.replace(/["']/g, '').replace(/\s+/g, '').toLowerCase();
}
